function push(
  out: Map<string, EvalCase>,
  text: string,
  expect: string,
  tag: EvalTag,
  source: string,
): void {
  const seen = out.get(text)
  if (!seen) {
    out.set(text, { text, expect, tags: [tag], source })
    return
  }
  if (seen.expect !== expect) {
    throw new Error(
      `Korpus widerspricht sich: ${JSON.stringify(text)} soll ${seen.expect} (${seen.source}) und ${expect} (${source}) sein`,
    )
  }
  if (!seen.tags.includes(tag)) seen.tags.push(tag)
}

let cache: EvalCase[] | null = null

/**
 * Alle Fälle, entdoppelt. Steht derselbe Prompt zweimal mit **verschiedener**
 * Erwartung, wirft das hier — genau der Fall, der vorher unbemerkt blieb.
 */
export function evalCases(): EvalCase[] {
  if (cache) return cache
  const out = new Map<string, EvalCase>()
  for (const [text, expect] of Object.entries(GOLD_EXPECT)) push(out, text, expect, 'gold', 'test-prompts')
  for (const [text, expect] of Object.entries(LOCK_EXPECT)) push(out, text, expect, 'lock', 'matrix-6.60')
  for (const [text, expect] of Object.entries(REGRESS_EXPECT)) push(out, text, expect, 'regress', 'sprints-115-120')
  for (const [text, expect] of Object.entries(STT_EXPECT)) push(out, text, expect, 'stt', 'sprachmodus')
  cache = [...out.values()]
  return cache
}

export function casesWithTag(tag: EvalTag): EvalCase[] {
  return evalCases().filter((c) => c.tags.includes(tag))
}
