// Recomputes effects and Spell/Trap subtypes of the bundled real cards with the current effect parser.
// Usage: node --experimental-strip-types scripts/enrich-ygo-effects.mjs
// Needs network access to the YGOPRODeck API. Card text is only read, never stored in the repository.
import { writeFileSync } from 'node:fs'
import { effectFromDescription } from '../src/engine/yugioh-duel.ts'

const target = new URL('../src/engine/yugioh-real-decks.ts', import.meta.url)
const { REAL_CARDS, REAL_DECKS } = await import(target.href)
const ids = Object.keys(REAL_CARDS).map(Number)
const info = new Map()
for (let index = 0; index < ids.length; index += 80) {
  const batch = ids.slice(index, index + 80)
  const response = await fetch(`https://db.ygoprodeck.com/api/v7/cardinfo.php?id=${batch.join(',')}`)
  if (!response.ok) throw new Error(`YGOPRODeck HTTP ${response.status}`)
  for (const card of (await response.json()).data) info.set(card.id, card)
  await new Promise((resolve) => setTimeout(resolve, 150))
}
const cards = {}
let withEffect = 0
for (const id of ids) {
  const { effect: _effect, effectSummary: _summary, subtype: _subtype, ...rest } = REAL_CARDS[id]
  const api = info.get(id)
  const parsed = api && !/Normal/.test(api.type) ? effectFromDescription(api.desc || '') : null
  if (parsed) withEffect += 1
  cards[id] = {
    ...rest,
    ...(rest.kind !== 'monster' && api?.race ? { subtype: api.race } : {}),
    ...(parsed ? { effect: parsed.effect, effectSummary: parsed.summary } : {}),
  }
}
const header = `// Generated by scripts/build-ygo-decks.mjs and scripts/enrich-ygo-effects.mjs. Do not edit by hand.
// Deck lists: official TCG-EN Structure Deck contents (Yugipedia set lists, with copy counts).
// Card data: YGOPRODeck API. Card images are loaded from images.ygoprodeck.com at runtime.
import type { DuelCard } from './yugioh-duel.ts'

type RealCard = Omit<DuelCard, 'id' | 'catalogId' | 'imageUrl' | 'copyLimit'>
export type RealDeck = { id: string; title: string; ultron: boolean; main: [number, number][]; extra: [number, number][] }

`
writeFileSync(target, `${header}export const REAL_CARDS: Record<number, RealCard> = ${JSON.stringify(cards)}\nexport const REAL_DECKS: readonly RealDeck[] = ${JSON.stringify(REAL_DECKS)}\n`)
console.error(`${ids.length} Karten, ${info.size} gefunden, ${withEffect} mit simuliertem Effekt`)
const kinds = {}
for (const card of Object.values(cards)) if (card.effect) kinds[card.effect.kind] = (kinds[card.effect.kind] || 0) + 1
console.error(kinds)
