// Regenerates src/engine/yugioh-real-decks.ts from structure-deck lists (Yugipedia set lists)
// and card data (YGOPRODeck API) prepared in a work directory: node build-ygo-decks.mjs <dir>
import { readFileSync, writeFileSync } from 'node:fs'
import { effectFromDescription } from '../src/engine/yugioh-duel.ts'

const dir = process.argv[2] || '/tmp/sd'
const decks = JSON.parse(readFileSync(`${dir}/decks.json`, 'utf8'))
const api = JSON.parse(readFileSync(`${dir}/api.json`, 'utf8'))

const fix = (name) => name.replace(/ \(card\)$/, '')
const extraKindOf = (frame) => (['fusion', 'synchro', 'xyz', 'link'].find((k) => frame.startsWith(k)))

const cardIndex = new Map()
const deckOut = []
for (const [title, list] of Object.entries(decks)) {
  const main = []
  const extra = []
  let dropped = 0
  for (const [rawName, qty] of Object.entries(list)) {
    const card = api[fix(rawName).toLowerCase()]
    if (!card || /token|skill/i.test(card.type)) { dropped += qty; continue }
    const extraKind = extraKindOf(card.frameType || '')
    if (!cardIndex.has(card.id)) {
      const parsed = /Normal/.test(card.type) ? null : effectFromDescription(card.desc || '')
      const type = card.type
      const kind = /spell/i.test(type) ? 'spell' : /trap/i.test(type) ? 'trap' : 'monster'
      cardIndex.set(card.id, {
        id: card.id, name: card.name, type, kind,
        ...(typeof card.atk === 'number' ? { atk: card.atk } : {}),
        ...(typeof card.def === 'number' ? { def: card.def } : {}),
        ...(typeof card.level === 'number' ? { level: card.level } : {}),
        ...(typeof card.linkval === 'number' ? { linkRating: card.linkval } : {}),
        ...(kind !== 'monster' && card.race ? { subtype: card.race } : {}),
        ...(/Tuner/.test(type) ? { tuner: true } : {}),
        ...(extraKind ? { extraKind, extraDeck: true } : {}),
        ...(parsed ? { effect: parsed.effect, effectSummary: parsed.summary } : {}),
      })
    }
    ;(extraKind ? extra : main).push([card.id, qty])
  }
  const count = (rows) => rows.reduce((s, [, q]) => s + q, 0)
  deckOut.push({ title, main, extra, mainCount: count(main), extraCount: count(extra), dropped })
}
const valid = deckOut.filter((d) => d.mainCount >= 40 && d.mainCount <= 60 && d.extraCount <= 15 && d.dropped === 0)
console.error('valid', valid.length, 'of', deckOut.length)
for (const d of deckOut) console.error(d.mainCount, d.extraCount, d.dropped, d.title, valid.includes(d) ? '' : 'SKIP')
const slug = (title) => title.replace(/ Structure Deck$/, '').replace(/^Structure Deck: /, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const ULTRON_POOL = [
  'Structure Deck: Blaze of Destruction', 'Structure Deck: Blue-Eyes White Destiny', 'Structure Deck: Cyber Strike',
  'Structure Deck: Cyberse Link', 'Structure Deck: Dark World', "Structure Deck: Dinosaur's Rage", "Structure Deck: Dragon's Roar",
  'Dragons Collide Structure Deck', 'Dragunity Legion Structure Deck', 'Emperor of Darkness Structure Deck', 'Structure Deck: Fire Kings',
  'Structure Deck: Freezing Chains', 'Structure Deck: Fury from the Deep', 'Gates of the Underworld Structure Deck',
  'Geargia Rampage Structure Deck', 'HERO Strike Structure Deck', 'Structure Deck: Lair of Darkness', 'Structure Deck: Lord of the Storm',
  'Machina Mayhem Structure Deck', 'Master of Pendulum Structure Deck', 'Structure Deck: Order of the Spellcasters',
  'Structure Deck: Rokket Revolt', 'Saga of Blue-Eyes White Dragon Structure Deck', 'Structure Deck: Seto Kaiba', 'Structure Deck: Yugi Muto',
]
for (const title of ULTRON_POOL) if (!valid.some((d) => d.title === title)) throw new Error(`Ultron-Deck fehlt: ${title}`)
const used = new Set(valid.flatMap((d) => [...d.main, ...d.extra].map(([id]) => id)))
const cards = Object.fromEntries([...cardIndex.values()].filter((c) => used.has(c.id)).map((c) => {
  const { id, ...rest } = c
  return [id, rest]
}))
const deckList = valid.map((d) => ({ id: slug(d.title), title: d.title.replace(/ Structure Deck$/, '').replace(/^Structure Deck: /, ''), ultron: ULTRON_POOL.includes(d.title), main: d.main, extra: d.extra }))
const header = `// Generated by scripts/build-ygo-decks.mjs. Do not edit by hand.
// Deck lists: official TCG-EN Structure Deck contents (Yugipedia set lists, with copy counts).
// Card data: YGOPRODeck API. Card images are loaded from images.ygoprodeck.com at runtime.
import type { DuelCard } from './yugioh-duel.ts'

type RealCard = Omit<DuelCard, 'id' | 'catalogId' | 'imageUrl' | 'copyLimit'>
export type RealDeck = { id: string; title: string; ultron: boolean; main: [number, number][]; extra: [number, number][] }

`
const footer = `
export const REAL_CARDS: Record<number, RealCard> = ${JSON.stringify(cards)}
export const REAL_DECKS: readonly RealDeck[] = ${JSON.stringify(deckList)}
`
writeFileSync(new URL('../src/engine/yugioh-real-decks.ts', import.meta.url), header + footer.trimStart() + '\n')
console.error('wrote', deckList.length, 'decks,', Object.keys(cards).length, 'cards, ultron pool', deckList.filter((d) => d.ultron).length)
writeFileSync(`${dir}/valid.json`, JSON.stringify({ valid: valid.map((d) => d.title), cards: [...cardIndex.values()], decks: deckOut }))
